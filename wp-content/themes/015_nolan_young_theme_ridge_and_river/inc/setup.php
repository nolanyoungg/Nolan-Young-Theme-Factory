<?php
/** Ridge & River WordPress support. */
if ( ! defined( 'ABSPATH' ) ) { exit; }
function ridge_river_setup() {
	load_theme_textdomain( '015-nolan-young-theme-ridge-and-river', get_template_directory() . '/languages' );
	add_theme_support( 'title-tag' );
	add_theme_support( 'post-thumbnails' );
	add_theme_support( 'responsive-embeds' );
	add_theme_support( 'align-wide' );
	add_theme_support( 'editor-styles' );
	add_editor_style( 'assets/css/bundle.css' );
	add_theme_support( 'html5', array( 'search-form', 'comment-form', 'comment-list', 'gallery', 'caption', 'style', 'script' ) );
}
add_action( 'after_setup_theme', 'ridge_river_setup' );

